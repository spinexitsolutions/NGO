import type { FieldDef } from './fields.js';
import type { Permission } from './permissions.js';
import { ICONS } from './enums.js';

/**
 * Content collections managed through the generic CMS CRUD API (`/api/v1/admin/collections/:key`)
 * and the generic admin editor. Each field maps 1:1 to a column of the Prisma model.
 */
export interface CollectionDef {
  key: string;
  model: string; // Prisma delegate name (camelCase)
  label: string;
  singular: string;
  description: string;
  permission: Permission;
  /** Moving a record into a public status additionally requires this permission. */
  publishPermission?: Permission;
  fields: FieldDef[];
  statusOptions: readonly { value: string; label: string }[];
  publicStatuses: readonly string[];
  listColumns: string[];
  searchFields: string[];
  orderBy: Record<string, 'asc' | 'desc'>[];
  hasSlug: boolean;
  titleField: string;
  /** Fields never returned by public endpoints. */
  privateFields?: string[];
  /** Business rules checked on save (returns error messages keyed by field). */
  rules?: (data: Record<string, unknown>) => Record<string, string | undefined>;
  /** Public URL prefix for "view on site" links */
  publicPath?: string;
}

